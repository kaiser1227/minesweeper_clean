  static String lookup(String key, [Locale? loc]) {
    final languageCode = loc?.languageCode ?? 'en';
    final scriptOrCountry = loc?.countryCode ?? '';

    // Check specific locale key first (e.g. zh_TW)
    if (languageCode == 'zh') {
      if (scriptOrCountry.toUpperCase() == 'TW' ||
          scriptOrCountry.toUpperCase() == 'HK') {
        final val = _localizedValues['zh_TW']?[key];
        if (val != null) return val;
      }
      final val = _localizedValues['zh_CN']?[key];
      if (val != null) return val;
    }

    final map = _localizedValues[languageCode] ?? _localizedValues['en']!;
    return map[key] ?? _localizedValues['en']?[key] ?? key;
  }

